/**
Generated-output gate contracts.

`scripts/check-generated.mjs` is a script, not a helper, so it can only be
exercised by running it. Each case builds a throwaway Git repository whose
generated inventory is wrong in exactly one way — stale, missing, untracked, or
absent entirely — and asserts the gate's exit status. Without these, a gate that
always exited `0` would pass the real repository too.
*/

import { describe, expect, test } from "bun:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

describe("generated-output gate", () => {
  const script = join(process.cwd(), "scripts", "check-generated.mjs");
  const generated = "// Generated by ReScript, PLEASE EDIT WITH CARE\n";
  const git = (directory, ...args) => {
    const result = Bun.spawnSync(["git", ...args], {
      cwd: directory,
      env: {
        ...process.env,
        GIT_AUTHOR_NAME: "contract fixture",
        GIT_AUTHOR_EMAIL: "fixture@example.invalid",
        GIT_COMMITTER_NAME: "contract fixture",
        GIT_COMMITTER_EMAIL: "fixture@example.invalid",
      },
    });
    assert.equal(
      result.exitCode,
      0,
      `git ${args.join(" ")}\n${result.stdout}\n${result.stderr}`,
    );
  };
  const runGate = (directory) =>
    Bun.spawnSync([process.execPath, script], { cwd: directory }).exitCode;
  const fixture = (prepare) => {
    const directory = mkdtempSync(join(tmpdir(), "refex-generated-"));
    try {
      git(directory, "init", "--quiet");
      mkdirSync(join(directory, "src"));
      prepare(directory);
      return runGate(directory);
    } finally {
      rmSync(directory, { recursive: true, force: true });
    }
  };

  // Every case below shells out to `git` several times and then runs the
  // gate as a subprocess. Bun's implicit 5s default is a wall-clock limit on
  // a shared machine rather than a property of the gate, so each test states
  // its own budget instead of inheriting one that fails under load.
  const budget = 30_000;

  test(
    "accepts committed output that matches the worktree",
    () => {
      expect(
        fixture((directory) => {
          writeFileSync(join(directory, "src/Module.res.mjs"), generated);
          git(directory, "add", "--", "src");
          git(directory, "commit", "--quiet", "--message", "generated output");
        }),
      ).toBe(0);
    },
    budget,
  );

  test(
    "rejects output that is committed but stale in the worktree",
    () => {
      expect(
        fixture((directory) => {
          writeFileSync(join(directory, "src/Module.res.mjs"), generated);
          git(directory, "add", "--", "src");
          git(directory, "commit", "--quiet", "--message", "generated output");
          writeFileSync(
            join(directory, "src/Module.res.mjs"),
            `${generated}// drifted\n`,
          );
        }),
      ).not.toBe(0);
    },
    budget,
  );

  test(
    "rejects generated output that is missing from the worktree",
    () => {
      expect(
        fixture((directory) => {
          writeFileSync(join(directory, "src/Module.res.mjs"), generated);
          git(directory, "add", "--", "src");
          git(directory, "commit", "--quiet", "--message", "generated output");
          rmSync(join(directory, "src/Module.res.mjs"));
        }),
      ).not.toBe(0);
    },
    budget,
  );

  test(
    "rejects generated output that is present but untracked",
    () => {
      expect(
        fixture((directory) => {
          writeFileSync(join(directory, "src/Module.res.mjs"), generated);
          git(directory, "add", "--", "src");
          git(directory, "commit", "--quiet", "--message", "generated output");
          writeFileSync(join(directory, "src/Extra.res.mjs"), generated);
        }),
      ).not.toBe(0);
    },
    budget,
  );

  test(
    "rejects a repository with no committed production output",
    () => {
      expect(
        fixture((directory) => {
          writeFileSync(join(directory, "src/Module.res"), "let x = 1\n");
          git(directory, "add", "--", "src");
          git(directory, "commit", "--quiet", "--message", "source only");
        }),
      ).not.toBe(0);
    },
    budget,
  );
});
